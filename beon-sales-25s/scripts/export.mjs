import {bundle} from '@remotion/bundler';
import {getCompositions,renderMedia} from '@remotion/renderer';
import {mkdir,rename} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import path from 'node:path';
const serveUrl=await bundle({entryPoint:path.resolve('src/index.ts')});
const browserExecutable=process.env.CHROME_PATH||'/usr/bin/chromium';
const chromiumOptions={gl:'swangle'};
const compositions=await getCompositions(serveUrl,{browserExecutable,chromiumOptions});
const composition=compositions.find(c=>c.id==='BeOn-Sales-25s');
if(!composition||composition.durationInFrames!==750||composition.fps!==30||composition.width!==1920||composition.height!==1080)throw Error('Unexpected composition metadata');
await mkdir('exports',{recursive:true});
let checkpoint=-1;
const outputLocation=path.resolve('exports/BeOn_Sales_25s.mp4');
console.log('Rendering 750 frames, Three.js with SwiftShader.');
await renderMedia({serveUrl,composition,browserExecutable,chromiumOptions,codec:'h264',crf:18,pixelFormat:'yuv420p',audioCodec:'aac',audioBitrate:'192k',concurrency:2,outputLocation,timeoutInMilliseconds:120000,onProgress:({progress})=>{const tick=Math.floor(progress*20);if(tick>checkpoint){checkpoint=tick;console.log('Render progress',Math.round(progress*100)+'%');}}});
const exact=outputLocation.replace(/\.mp4$/,'.exact.mp4');
execFileSync('ffmpeg',['-y','-v','error','-i',outputLocation,'-t','25','-c:v','copy','-c:a','aac','-b:a','192k','-ar','48000','-af','atrim=duration=25','-movflags','+faststart',exact]);
await rename(exact,outputLocation);
console.log('Export completed:',outputLocation);
